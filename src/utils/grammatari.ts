/**
 * Letter frequency counter for sub-anagram solver
 */
export function getLetterFrequencies(text: string): Record<string, number> {
  const freqs: Record<string, number> = {};
  const cleaned = text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^Α-Ω]/g, "");

  for (const char of cleaned) {
    const canonical = char === "ς" || char === "Σ" ? "Σ" : char;
    freqs[canonical] = (freqs[canonical] || 0) + 1;
  }
  return freqs;
}

/**
 * Check if candidate word can be formed strictly using a subset of available letters
 * without exceeding any individual letter count.
 * E.g., if input phrase has one 'A', candidate cannot use two 'A's (such as 'ΑΙΑΣ').
 */
export function canFormWordStrict(candidate: string, availableFrequencies: Record<string, number>): boolean {
  const candidateFreqs = getLetterFrequencies(candidate);
  for (const [letter, neededCount] of Object.entries(candidateFreqs)) {
    const availableCount = availableFrequencies[letter] || 0;
    if (neededCount > availableCount) {
      return false;
    }
  }
  return true;
}

export const canFormWord = canFormWordStrict;

export interface GrammatariMatch {
  word: string;
  length: number;
  isopsephy: number;
  pythmen: number;
  letterBreakdown: string;
}

/**
 * Main Grammatari sub-anagram engine
 * Enforces strict anagram matching: every letter must exist in the source phrase
 * and cannot exceed its available frequency.
 */
export function solveGrammatari(
  inputPhrase: string,
  minLen: number = 2,
  maxLen: number = 16,
  customWordBank: string[] = []
): {
  availableLetters: { letter: string; count: number }[];
  totalAvailableLetters: number;
  sourceIsopsephy: number;
  sourcePythmen: number;
  matchesByLength: Record<number, GrammatariMatch[]>;
  totalMatches: number;
} {
  const freqs = getLetterFrequencies(inputPhrase);
  const availableLetters = Object.entries(freqs)
    .map(([letter, count]) => ({ letter, count }))
    .sort((a, b) => b.count - a.count || a.letter.localeCompare(b.letter));

  const totalAvailableLetters = Object.values(freqs).reduce((a, b) => a + b, 0);

  const IONIAN_MAP: Record<string, number> = {
    Α: 1, Β: 2, Γ: 3, Δ: 4, Ε: 5, Ϛ: 6, Ζ: 7, Η: 8, Θ: 9,
    Ι: 10, Κ: 20, Λ: 30, Μ: 40, Ν: 50, Ξ: 60, Ο: 70, Π: 80, Ϟ: 90,
    Ρ: 100, Σ: 200, Τ: 300, Υ: 400, Φ: 500, Χ: 600, Ψ: 700, Ω: 800, Ϡ: 900
  };

  // Compute source phrase isopsephy
  let sourceIsopsephy = 0;
  const cleanInput = inputPhrase
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^Α-Ω]/g, "");

  for (const char of cleanInput) {
    sourceIsopsephy += IONIAN_MAP[char] || 0;
  }

  let sourcePythmen = sourceIsopsephy;
  while (sourcePythmen > 9) {
    sourcePythmen = sourcePythmen.toString().split("").reduce((acc, digit) => acc + parseInt(digit, 10), 0);
  }

  // Combine core database, extended classical lexicon, and any custom words
  const pool = Array.from(new Set([...GREEK_WORDS_DATABASE, ...GREEK_EXTENDED_LEXICON, ...customWordBank]));

  const matchesByLength: Record<number, GrammatariMatch[]> = {};
  let totalMatches = 0;

  for (let l = minLen; l <= maxLen; l++) {
    matchesByLength[l] = [];
  }

  for (const rawWord of pool) {
    const cleanW = rawWord
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toUpperCase()
      .replace(/[^Α-Ω]/g, "");

    const wLen = cleanW.length;
    if (wLen >= minLen && wLen <= maxLen) {
      // Must strictly not exceed available count of any letter in source phrase
      if (canFormWordStrict(cleanW, freqs)) {
        // Prevent duplicate word entries
        if (!matchesByLength[wLen].some((m) => m.word === cleanW)) {
          // Calculate simple Ionian Isopsephy and Pythmen
          let sum = 0;
          const parts: string[] = [];

          for (const char of cleanW) {
            const val = IONIAN_MAP[char] || 0;
            sum += val;
            parts.push(`${char}(${val})`);
          }

          let pyth = sum;
          while (pyth > 9) {
            pyth = pyth.toString().split("").reduce((acc, digit) => acc + parseInt(digit, 10), 0);
          }

          matchesByLength[wLen].push({
            word: cleanW,
            length: wLen,
            isopsephy: sum,
            pythmen: pyth,
            letterBreakdown: parts.join(" + "),
          });
          totalMatches++;
        }
      }
    }
  }

  // Sort each group by isopsephy or alphabetically
  for (let l = minLen; l <= maxLen; l++) {
    matchesByLength[l].sort((a, b) => b.isopsephy - a.isopsephy || a.word.localeCompare(b.word));
  }

  return {
    availableLetters,
    totalAvailableLetters,
    sourceIsopsephy,
    sourcePythmen,
    matchesByLength,
    totalMatches,
  };
}
